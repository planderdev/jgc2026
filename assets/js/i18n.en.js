  function lower(s) { return s.length > 1 && /^[A-Z][a-z]/.test(s) ? s[0].toLowerCase() + s.slice(1) : s; }

  function tr(text) {
    const key = text.replace(/\s+/g, ' ').trim();
    if (!/[가-힣]/.test(key)) return text;
    if (D[key] !== undefined) return D[key];
    for (const [re, fn] of R) { const m = key.match(re); if (m) return fn(m); }
    return text;
  }

  const ATTRS = ['placeholder', 'title', 'aria-label', 'alt'];

  function translateNode(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      if (!/[가-힣]/.test(node.nodeValue)) return;
      const parent = node.parentElement;
      if (!parent || parent.closest('script, style, [data-no-i18n]')) return;
      const out = tr(node.nodeValue);
      if (out !== node.nodeValue) {
        // 원문의 앞뒤 공백은 유지한다(인라인 요소 사이 간격).
        const lead = node.nodeValue.match(/^\s*/)[0];
        const tail = node.nodeValue.match(/\s*$/)[0];
        node.nodeValue = lead + out + tail;
      }
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE) return;
    if (node.closest('script, style, [data-no-i18n]')) return;
    ATTRS.forEach((a) => {
      const v = node.getAttribute(a);
      if (v && /[가-힣]/.test(v)) { const out = tr(v); if (out !== v) node.setAttribute(a, out); }
    });
    // innerHTML로 한 번에 그린 큰 덩어리도 안쪽까지 훑는다.
    const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    let n;
    while ((n = walker.nextNode())) {
      if (n.nodeType === Node.TEXT_NODE) translateNode(n);
      else ATTRS.forEach((a) => { const v = n.getAttribute(a); if (v && /[가-힣]/.test(v)) { const out = tr(v); if (out !== v) n.setAttribute(a, out); } });
    }
  }

  function translateAll() { translateNode(document.body); }

  const observer = new MutationObserver((records) => {
    for (const r of records) {
      if (r.type === 'characterData') translateNode(r.target);
      else if (r.type === 'attributes') translateNode(r.target);
      else r.addedNodes.forEach(translateNode);
    }
  });

  function start() {
    translateAll();
    observer.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start);
